const PLACES = new Map(ROWS.map((r) => [r[0], { province: r[1] || '', city: r[2] || '' }]));

/** 这个名字在名单里吗（就是这一条挡住了手填的假学校） */
export function isKnownSchool(name) {
  return PLACES.has(String(name || '').trim());
}

/** 学校在哪（「省份 城市」），查不到返回空串 */
export function schoolPlace(name) {
  const p = PLACES.get(String(name || '').trim());
  if (!p) return '';
  return [p.province, p.city].filter(Boolean).join(' ');
}
