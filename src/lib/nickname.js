/**
 * 昵称里不允许出现的词。
 *
 * 为什么要有这个：社区里的资料卡片会写成「<昵称> 公开了这份资料」。
 * 所以一个叫「爸爸」的人公开一份资料，页面上就是**替他**对所有同校同学
 * 喊了一句「爸爸 公开了这份资料」。这不是"名字取得不好听"，而是拿页面
 * 当工具去占别人便宜 —— 而且被冒犯的人什么都没做，只是打开了一个页面。
 * 「主人 / 奴才 / 少爷」这类主仆尊卑词是同一类问题的另一面（把别人往下压）。
 *
 * ## 匹配方式与它的代价
 *
 * 用的是**子串匹配**（`name.includes(word)`），因为中文没有词边界，
 * 靠分词既不可靠又要引入依赖（这个项目是零依赖的）。
 * 子串匹配的代价是**可能误伤**，所以词表有几个硬规矩：
 *
 * ⚠️ **不收单字**，除非那个字几乎不会出现在别的词里。
 *    - 不收 `母`：会把「字母」「母校」「酵母」一起挡掉
 *    - 不收 `父`：会把「师父」一起挡掉
 *    - 不收 `娘`：会把「姑娘」一起挡掉
 *    - 不收 `哥`：会把「大哥」一起挡掉
 *    → 所以这里全是「两个字的完整称谓」。「姑娘」「师父」「字母」「大哥」
 *      都能正常用，而且自测里**专门钉了这几个**（只钉"该挡的挡住了"是不够的，
 *      还得钉"不该挡的没挡"，否则词表会越收越宽、最后谁的名字都过不了）。
 *
 * ⚠️ 加词之前先想一遍：这个词会不会出现在某个正常词里面？
 *    拿不准就自己造一个更长的写法（比如用「老妈」而不是「妈」）。
 */
export const BANNED_NICKNAME_WORDS = [
  // 亲属称谓：拿它当昵称，等于让页面替他跟别人认亲
  '父亲', '爸爸', '老爸', '爹', '爹爹', '父上',
  '母亲', '妈妈', '老妈', '娘亲', '母上',
  '爷爷', '奶奶', '外公', '外婆', '姥姥', '姥爷',
  '哥哥', '弟弟', '姐姐', '妹妹', '儿子', '女儿', '孙子', '孙女',
  '老公', '老婆', '妻子', '丈夫', '夫君', '娘子', '夫人', '太太',
  '叔叔', '阿姨', '舅舅', '姑姑', '伯伯', '舅妈', '姨妈', '姑父',
  // 主仆 / 尊卑：自称或让人这么叫，都是把别人往下压
  '主人', '主子', '奴隶', '奴才', '奴婢', '仆人', '少爷', '老爷', '祖宗',
];

/** 给用户看的占位说法：昵称被禁时，别人那一侧看到的东西 */
export const NICKNAME_PLACEHOLDER = '（昵称待修改）';

/**
 * 昵称里有没有不允许的词。返回命中的那个词，没有则返回空串。
 *
 * 大小写和全角半角都归一再比：`ＢＡＢＡ` 这种形状上的绕道没必要单独防，
 * 但英文字母的大小写顺手统一一下不要钱（将来加英文词表时也用得上）。
 */
export function bannedWordIn(raw) {
  const name = String(raw ?? '')
    .normalize('NFKC')          // 全角 → 半角
    .toLowerCase();
  if (!name) return '';
  for (const w of BANNED_NICKNAME_WORDS) {
    if (name.includes(w.normalize('NFKC').toLowerCase())) return w;
  }
  return '';
}

/** 这个昵称是不是被禁了 */
export function isNicknameBanned(raw) {
  return Boolean(bannedWordIn(raw));
}

/**
 * 校验昵称。有问题返回一句中文说明，没问题返回空字符串
 * —— 和 auth.js 里 usernameProblem / passwordProblem 一样的形状。
 *
 * **把命中的那个词说出来**：不告诉用户是哪个词，他只会一次次试、
 * 一次次被拒，最后干脆放弃填昵称。这个词表不是秘密，也没有"知道了就能绕"
 * 的问题 —— 我们要的是他换一个，不是他猜不到。
 */
export function nicknameProblem(raw) {
  const name = String(raw ?? '').trim();
  if (!name) return '';                       // 空昵称是允许的（只是进不了社区）
  const hit = bannedWordIn(name);
  if (!hit) return '';
  return `昵称里不能出现「${hit}」这类称呼 —— 社区里会把昵称显示在资料上`
    + `（「${hit} 公开了这份资料」读起来是把别人当下辈），换一个吧。`;
}

/**
 * 拿去**给别人看**的昵称。
 *
 * 被禁的昵称统一返回空串，调用方原有的兜底就都生效了
 * （社区里显示「（没填昵称）」、头像显示问号）——
 * 这样"封禁"是**读的时候生效**的，不用去改用户的数据：
 *   · 他填的东西还在自己设置页里，改一个词就立刻恢复；
 *   · 不用写迁移去批量清库，也不会有"我填的名字怎么没了"这种事。
 * 比"把库里那行改掉"更可逆，也更容易解释。
 */
export function safeDisplayName(raw) {
  return isNicknameBanned(raw) ? '' : String(raw ?? '');
}
